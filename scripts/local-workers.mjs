async function prepareClamav(contract) {
  const image = contract.clamav.updaterImage;
  if (!(await commandSucceeds("podman", ["image", "exists", image]))) {
    console.info("Pulling digest-pinned ClamAV development updater");
    await runCommand(
      "podman",
      ["pull", "--platform", contract.ingestion.platform, image],
      { timeout: 10 * 60_000 },
    );
  }
  await verifyUpdaterImage(contract);

  const targetDirectory = path.join(generatedRoot, "clamav");
  let reuseExistingSnapshot = false;
  if (await pathExists(targetDirectory)) {
    try {
      const existing = await inspectClamavDirectory(contract, targetDirectory);
      console.info(
        `Reusing fresh ClamAV ${contract.clamav.version} snapshot ${existing.dailyBuiltAt}`,
      );
      return {
        ...existing,
        directory: targetDirectory,
        updaterImage: image,
      };
    } catch (error) {
      if (
        error instanceof LocalWorkerError &&
        error.state !== "STALE" &&
        error.state !== "INVALID"
      ) {
        throw error;
      }
      reuseExistingSnapshot =
        error instanceof LocalWorkerError && error.state === "STALE";
      console.info("Refreshing stale or invalid ClamAV development signatures");
    }
  }
  const nextDirectory = path.join(generatedRoot, ".clamav-next");
  const previousDirectory = path.join(generatedRoot, ".clamav-previous");
  await rm(nextDirectory, { force: true, recursive: true });
  await ensureDirectory(nextDirectory);
  if (reuseExistingSnapshot) {
    await cp(targetDirectory, nextDirectory, {
      errorOnExist: false,
      force: true,
      recursive: true,
    });
  } else if (!(await pathExists(targetDirectory))) {
    const legacy = path.join(
      repositoryRoot,
      ".reflo",
      "local-smoke",
      "clamav-database",
    );
    if (await pathExists(legacy)) {
      await cp(legacy, nextDirectory, {
        errorOnExist: false,
        force: true,
        recursive: true,
      });
    }
  }
  await chmod(nextDirectory, 0o700);
  console.info("Refreshing ClamAV development signatures with FreshClam");
  try {
    await runCommand(
      "podman",
      [
        "run",
        "--rm",
        "--pull=never",
        "--cap-drop=ALL",
        "--security-opt=no-new-privileges",
        "--read-only",
        "--user=100:101",
        "--userns=keep-id:uid=100,gid=101",
        "--tmpfs=/tmp:rw,noexec,nosuid,nodev,size=268435456",
        `--mount=type=bind,src=${nextDirectory},dst=/database,rw=true,relabel=private`,
        "--entrypoint=/usr/bin/freshclam",
        image,
        "--stdout",
        "--log=/tmp/freshclam.log",
        "--datadir=/database",
      ],
      { maxBuffer: 4 * maximumCommandOutputBytes, timeout: 10 * 60_000 },
    );
    const snapshot = await inspectClamavDirectory(contract, nextDirectory);
    await rm(previousDirectory, { force: true, recursive: true });
    if (await pathExists(targetDirectory)) {
      await rename(targetDirectory, previousDirectory);
    }
    await rename(nextDirectory, targetDirectory);
    await rm(previousDirectory, { force: true, recursive: true });
    console.info(
      `Verified ClamAV ${contract.clamav.version} snapshot ${snapshot.dailyBuiltAt}`,
    );
    return {
      ...snapshot,
      directory: targetDirectory,
      updaterImage: image,
    };
  } catch (error) {
    await rm(nextDirectory, { force: true, recursive: true });
    if (error instanceof LocalWorkerError) throw error;
    throw new LocalWorkerError(
      "INVALID",
      "clamav",
      "FreshClam update failed; verify network access and retry",
    );
  }
}

