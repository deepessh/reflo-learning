async function runCommand(executable, args, options = {}) {
  try {
    const result = await execFileAsync(executable, args, {
      encoding: "utf8",
      env: options.env ?? process.env,
      maxBuffer: options.maxBuffer ?? maximumCommandOutputBytes,
      timeout: options.timeout ?? 60_000,
    });
    return {
      stderr: result.stderr ?? "",
      stdout: result.stdout ?? "",
    };
  } catch {
    throw new Error(`command failed: ${path.basename(executable)}`);
  }
}

function runWithInput(executable, args, input, environment, timeoutMs) {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, {
      env: environment,
      shell: false,
      stdio: ["pipe", "pipe", "pipe"],
    });
    let outputBytes = 0;
    const timer = setTimeout(() => child.kill("SIGKILL"), timeoutMs);
    const count = (chunk) => {
      outputBytes += chunk.byteLength;
      if (outputBytes > maximumCommandOutputBytes) child.kill("SIGKILL");
    };
    child.stdout.on("data", count);
    child.stderr.on("data", count);
    child.on("error", () => {
      clearTimeout(timer);
      reject(new Error("Piper process failed to launch"));
    });
    child.on("close", (code, signal) => {
      clearTimeout(timer);
      if (code === 0 && signal === null) {
        resolve();
      } else {
        reject(new Error("Piper process failed"));
      }
    });
    child.stdin.end(input);
  });
}

function usage() {
  console.info(`Usage: node scripts/local-workers.mjs <command>

Commands:
  prepare  Build/load and verify the optional ingestion and Piper profile.
  status   Report AVAILABLE, SKIPPED, STALE, UNSUPPORTED, or INVALID states.
  ready    Require every operator-hosted worker prerequisite to be AVAILABLE.
  smoke    Run the committed fixture through ingestion and produce a WAV.
  cleanup  Remove only the named Reflo image and generated worker profile.`);
}

async function main() {
  const command = process.argv[2];
  switch (command) {
    case "prepare":
      await prepare();
      return;
    case "status":
      await status();
      return;
    case "ready":
      await ready();
      return;
    case "smoke":
      await smoke();
      return;
    case "cleanup":
      await cleanup();
      return;
    case "help":
    case "--help":
    case "-h":
      usage();
      return;
    default:
      usage();
      process.exitCode = 2;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    if (error instanceof LocalWorkerError) {
      console.error(`${error.state} ${error.component}: ${error.action}`);
    } else {
      console.error("INVALID local-workers: unexpected failure");
    }
    process.exitCode = 1;
  });
}
