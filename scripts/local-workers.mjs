export function validateLocalWorkersContract(
  contract,
  ingestionManifest,
  piperManifest,
  containerfile,
) {
  const errors = [];
  if (
    contract.contractVersion !== "reflo-local-workers-v2" ||
    contract.stateVersion !== "reflo-local-workers-state-v2" ||
    contract.profile !== "development-only"
  ) {
    errors.push("invalid local-worker contract identity");
  }
  if (
    JSON.stringify(contract.supportedPodmanVersions) !==
    JSON.stringify(["5.8.3", "6.0.1"])
  ) {
    errors.push("Podman compatibility must be exactly 5.8.3 or 6.0.1");
  }
  if (
    contract.ingestion.imageReference !== "reflo-ingestion-worker:local" ||
    contract.ingestion.platform !== "linux/amd64" ||
    contract.ingestion.profile !== ingestionManifest.profile
  ) {
    errors.push("invalid development ingestion image contract");
  }
  if (
    contract.clamav.version !== "1.4.5" ||
    contract.clamav.version !==
      ingestionManifest.components.scanner.replace("clamav-", "") ||
    !contract.clamav.updaterImage.endsWith(
      `@${contract.clamav.updaterImageDigest}`,
    ) ||
    !digestPattern.test(contract.clamav.updaterImageDigest) ||
    contract.clamav.maxAgeHours !== 24 ||
    JSON.stringify(contract.clamav.allowedMetadataFiles) !==
      JSON.stringify(["freshclam.dat"])
  ) {
    errors.push("invalid development ClamAV contract");
  }
  if (
    !containerfile.includes(contract.tessdata.url) ||
    !containerfile.includes(contract.tessdata.sha256) ||
    !sha256Pattern.test(contract.tessdata.sha256)
  ) {
    errors.push("tessdata does not match the ingestion Containerfile");
  }
  if (contract.piper.pythonVersion !== piperManifest.baseImage.pythonVersion) {
    errors.push("Piper Python version does not match the checked-in manifest");
  }
  if (
    contract.piper.version !== piperManifest.piper.version ||
    contract.piper.voice.profileId !== piperManifest.voice.profileId ||
    contract.piper.voice.voiceId !== piperManifest.voice.voiceId ||
    contract.piper.voice.revision !== piperManifest.voice.revision ||
    contract.piper.voice.modelPath !== piperManifest.voice.modelPath ||
    contract.piper.voice.modelSha256 !== piperManifest.voice.modelSha256 ||
    contract.piper.voice.configPath !== piperManifest.voice.configPath ||
    contract.piper.voice.configSha256 !== piperManifest.voice.configSha256
  ) {
    errors.push("Piper voice inputs do not match the checked-in manifest");
  }
  const runtimeKeys = new Set();
  for (const runtime of contract.piper.runtimes ?? []) {
    if (
      runtimeKeys.has(runtime.platform) ||
      !/^(?:darwin|linux)\/(?:arm64|x64)$/.test(runtime.platform) ||
      !sha256Pattern.test(runtime.piperWheelSha256) ||
      !sha256Pattern.test(runtime.onnxRuntimeWheelSha256) ||
      !runtime.piperWheel.includes(`piper_tts-${contract.piper.version}-`) ||
      !runtime.onnxRuntimeWheel.includes(
        `onnxruntime-${runtime.onnxRuntimeVersion}-`,
      )
    ) {
      errors.push("invalid Piper development runtime pin");
      break;
    }
    runtimeKeys.add(runtime.platform);
  }
  if (runtimeKeys.size !== 4) {
    errors.push("Piper development runtime matrix is incomplete");
  }
  return errors;
}

async function loadContracts() {
  const [contract, ingestionManifest, piperManifest, containerfile] =
    await Promise.all([
      readJson(contractPath),
      readJson(
        path.join(repositoryRoot, "packages/ingestion/worker/manifest.json"),
      ),
      readJson(
        path.join(repositoryRoot, "packages/audio/piper-worker/manifest.json"),
      ),
      readFile(
        path.join(repositoryRoot, "packages/ingestion/worker/Containerfile"),
        "utf8",
      ),
    ]);
  const errors = validateLocalWorkersContract(
    contract,
    ingestionManifest,
    piperManifest,
    containerfile,
  );
  if (errors.length > 0) {
    throw new LocalWorkerError("INVALID", "contract", errors.join("; "));
  }
  return { contract, ingestionManifest };
}

async function prepare() {
  assertGeneratedRoot();
  const { contract, ingestionManifest } = await loadContracts();
  const runtime = selectPiperRuntime(contract);
  await ensureDirectory(generatedRoot);

  console.info("Preparing optional Reflo development workers");
  const podman = await verifyPodmanHost(contract);
  const ingestion = await runPreparationStep(
    "ingestion-worker",
    "failed to build or verify the local ingestion image",
    () => prepareIngestion(contract, ingestionManifest, podman),
  );
  const tessdata = await runPreparationStep(
    "tessdata",
    "failed to prepare checksum-pinned English tessdata",
    () => prepareTessdata(contract),
  );
  const piper = await runPreparationStep(
    "piper",
    "failed to prepare the pinned Piper development environment",
    () => preparePiper(contract, runtime),
  );
  const clamav = await runPreparationStep(
    "clamav",
    "failed to refresh and verify the ClamAV development snapshot",
    () => prepareClamav(contract),
  );
  const clamavAdmission = await runPreparationStep(
    "clamav-admission",
    "publish and verify the upstream-signed ClamAV admission snapshot",
    () => prepareClamavAdmission(contract, clamav),
  );
  const state = {
    contractVersion: contract.stateVersion,
    preparedAt: new Date().toISOString(),
    profile: contract.profile,
    hostPlatform: hostPlatformKey(),
    podmanClientVersion: podman.clientVersion,
    podmanServerVersion: podman.serverVersion,
    ingestion,
    clamav,
    clamavAdmission,
    tessdata,
    piper,
  };
  await writePrivateJson(statePath, state);
  await writePrivateFile(
    profileEnvironmentPath,
    renderProfileEnvironment(state),
  );

  const readiness = await collectReadiness(contract, ingestionManifest);
  printReadiness(readiness);
  if (!readiness.every((item) => item.state === "AVAILABLE")) {
    throw new LocalWorkerError(
      "INVALID",
      "local-workers",
      "preparation completed but readiness verification failed",
    );
  }
  console.info(`Profile environment: ${profileEnvironmentPath}`);
}

async function status() {
  const { contract, ingestionManifest } = await loadContracts();
  const readiness = await collectReadiness(contract, ingestionManifest);
  printReadiness(readiness);
}

async function ready() {
  const { contract, ingestionManifest } = await loadContracts();
  const readiness = await collectReadiness(contract, ingestionManifest);
  printReadiness(readiness);
  if (!readiness.every((item) => item.state === "AVAILABLE")) {
    throw new LocalWorkerError(
      "INVALID",
      "local-workers",
      "every operator-hosted worker prerequisite must be available",
    );
  }
}

async function smoke() {
  const { contract, ingestionManifest } = await loadContracts();
  const readiness = await collectReadiness(contract, ingestionManifest);
  printReadiness(readiness);
  if (!readiness.every((item) => item.state === "AVAILABLE")) {
    throw new LocalWorkerError(
      "INVALID",
      "local-workers-smoke",
      "prepare or repair the optional worker profile before smoke execution",
    );
  }
  const state = await readState(contract);
  const fixturePath = absoluteContractPath(contract.ingestion.fixture);
  const fixtureHash = await sha256File(fixturePath);
  const operationId = `localworker-${fixtureHash.slice(0, 16)}`;
  const jobRoot = path.join(generatedRoot, "smoke", `${operationId}-fixture`);
  const inputPath = path.join(jobRoot, "source");
  const outputDirectory = path.join(jobRoot, "output");
  await ensureDirectory(outputDirectory);
  if (!(await regularFileMatches(inputPath, fixtureHash).catch(() => false))) {
    await copyFile(fixturePath, inputPath);
    await chmod(inputPath, 0o400);
  }

  await runCommand(
    "podman",
    ingestionLaunchArguments({
      clamavDirectory: state.clamav.directory,
      components: ingestionManifest.components,
      imageDigest: state.ingestion.imageDigest,
      imageReference: state.ingestion.imageReference,
      inputPath,
      inputSha256: fixtureHash,
      operationId,
      outputDirectory,
      profile: contract.ingestion.profile,
      tessdataDirectory: state.tessdata.directory,
    }),
    { timeout: 120_000 },
  );
  const normalizedPath = path.join(outputDirectory, "normalized-document.json");
  const normalized = await readJson(normalizedPath);
  if (
    normalized.contractVersion !== "normalized-document-v1" ||
    !Array.isArray(normalized.blocks)
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-smoke",
      "worker output did not match normalized-document-v1",
    );
  }

  const audioPath = path.join(jobRoot, "piper.wav");
  await synthesizePiper(state.piper, audioPath);
  const audio = await inspectWav(audioPath);
  const summary = {
    contractVersion: "reflo-local-workers-smoke-v1",
    fixtureSha256: fixtureHash,
    normalizedDocumentSha256: await sha256File(normalizedPath),
    normalizedBlockCount: normalized.blocks.length,
    audioSha256: await sha256File(audioPath),
    audioBytes: audio.byteLength,
    audioSampleRate: audio.sampleRate,
    replaySafePaths: {
      normalizedDocument: normalizedPath,
      audio: audioPath,
    },
    productionEvidence: false,
  };
  console.info(`AVAILABLE local-workers-smoke: ${JSON.stringify(summary)}`);
}

async function cleanup() {
  assertGeneratedRoot();
  const { contract } = await loadContracts();
  if (
    await commandSucceeds("podman", [
      "image",
      "exists",
      contract.ingestion.imageReference,
    ])
  ) {
    const inspect = await inspectImage(contract.ingestion.imageReference);
    if (
      inspect.Config?.Labels?.["org.opencontainers.image.version"] !==
      contract.ingestion.profile
    ) {
      throw new LocalWorkerError(
        "INVALID",
        "cleanup",
        "the local image tag is not a Reflo isolated-ingestion image",
      );
    }
    await runCommand("podman", [
      "image",
      "rm",
      contract.ingestion.imageReference,
    ]);
    console.info(
      `Removed named Reflo image ${contract.ingestion.imageReference}`,
    );
  }
  await rm(generatedRoot, { force: true, recursive: true });
  console.info(`Removed generated worker profile ${generatedRoot}`);
  console.info(
    "Application artifacts, local databases, Podman VM, and the shared ClamAV updater image were preserved",
  );
}

async function collectReadiness(contract, ingestionManifest) {
  let podman;
  try {
    podman = await verifyPodmanHost(contract);
  } catch (error) {
    const item = readinessFromError(error, "podman");
    return [
      item,
      {
        state: "SKIPPED",
        component: "local-workers",
        message:
          "optional profile cannot be evaluated until Podman is supported",
      },
    ];
  }

  if (!(await pathExists(statePath))) {
    return [
      {
        state: "AVAILABLE",
        component: "podman",
        message: podmanReadinessMessage(podman),
      },
      {
        state: (await pathExists(generatedRoot)) ? "INVALID" : "SKIPPED",
        component: "local-workers",
        message: (await pathExists(generatedRoot))
          ? "incomplete profile; run corepack pnpm local-workers:prepare"
          : "optional profile is not prepared; run corepack pnpm local-workers:prepare",
      },
    ];
  }

  let state;
  try {
    state = await readState(contract);
  } catch (error) {
    return [
      {
        state: "AVAILABLE",
        component: "podman",
        message: podmanReadinessMessage(podman),
      },
      readinessFromError(error, "local-workers"),
    ];
  }
  const results = [
    {
      state: "AVAILABLE",
      component: "podman",
      message: podmanReadinessMessage(podman),
    },
  ];
  const checks = [
    [
      "ingestion-worker",
      () => verifyPreparedIngestion(contract, ingestionManifest, state),
    ],
    ["clamav", () => verifyPreparedClamav(contract, state)],
    ["clamav-admission", () => verifyPreparedClamavAdmission(contract, state)],
    ["tessdata", () => verifyPreparedTessdata(contract, state)],
    ["piper", () => verifyPreparedPiper(contract, state)],
    ["local-workers", () => verifyPreparedProfile(state)],
  ];
  for (const [component, check] of checks) {
    try {
      results.push(await check());
    } catch (error) {
      results.push(readinessFromError(error, component));
    }
  }
  return results;
}

function printReadiness(readiness) {
  for (const item of readiness) {
    console.info(`${item.state} ${item.component}: ${item.message}`);
  }
}

function readinessFromError(error, fallbackComponent) {
  if (error instanceof LocalWorkerError) {
    return {
      state: error.state,
      component: error.component,
      message: error.action,
    };
  }
  return {
    state: "INVALID",
    component: fallbackComponent,
    message: "unexpected verification failure; run local-workers:prepare",
  };
}

async function verifyPodmanHost(contract) {
  let versionOutput;
  try {
    versionOutput = (
      await runCommand("podman", ["version", "--format", "json"], {
        timeout: 10_000,
      })
    ).stdout.trim();
  } catch {
    throw new LocalWorkerError(
      "UNSUPPORTED",
      "podman",
      "install development-compatible Podman 5.8.3 or 6.0.1",
    );
  }
  const report = parsePodmanVersionReport(versionOutput);
  if (report === undefined) {
    throw new LocalWorkerError(
      "UNSUPPORTED",
      "podman",
      "could not read both Podman client and server versions",
    );
  }
  if (
    !podmanVersionReportIsSupported(report, contract.supportedPodmanVersions)
  ) {
    throw new LocalWorkerError(
      "UNSUPPORTED",
      "podman",
      `client ${report.clientVersion}, server ${report.serverVersion}; both must match at exactly 5.8.3 or 6.0.1`,
    );
  }
  const rootless = (
    await runPreparationStep(
      "podman",
      "start a supported rootless Podman connection and retry",
      () =>
        runCommand(
          "podman",
          ["info", "--format", "{{.Host.Security.Rootless}}"],
          { timeout: 10_000 },
        ),
    )
  ).stdout.trim();
  if (rootless !== "true") {
    throw new LocalWorkerError(
      "UNSUPPORTED",
      "podman",
      "the local Podman connection must be rootless",
    );
  }
  return report;
}

function podmanReadinessMessage(podman) {
  return `rootless development-compatible Podman client ${podman.clientVersion}, server ${podman.serverVersion}`;
}

async function prepareIngestion(contract, ingestionManifest, podman) {
  const imageReference = contract.ingestion.imageReference;
  const archive = process.env.REFLO_LOCAL_INGESTION_ARCHIVE;
  const archiveSha256 = process.env.REFLO_LOCAL_INGESTION_ARCHIVE_SHA256;
  const archiveConfigured = archive !== undefined && archive.length > 0;
  const archiveSha256Configured =
    archiveSha256 !== undefined && archiveSha256.length > 0;
  if (archiveConfigured !== archiveSha256Configured) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "set REFLO_LOCAL_INGESTION_ARCHIVE and REFLO_LOCAL_INGESTION_ARCHIVE_SHA256 together",
    );
  }
  let archiveLoaded = false;
  if (archiveConfigured) {
    const archivePath = safeAbsoluteInput(
      archive,
      "REFLO_LOCAL_INGESTION_ARCHIVE",
    );
    await verifyRegularFile(archivePath, "ingestion-worker");
    if (!sha256Pattern.test(archiveSha256)) {
      throw new LocalWorkerError(
        "INVALID",
        "ingestion-worker",
        "set REFLO_LOCAL_INGESTION_ARCHIVE_SHA256 for the configured archive",
      );
    }
    await requireDigest(archivePath, archiveSha256, "ingestion-worker");
    console.info(`Loading configured ingestion image archive ${archivePath}`);
    const loaded = await runCommand(
      "podman",
      ["load", "--input", archivePath],
      {
        timeout: 10 * 60_000,
      },
    );
    if (!`${loaded.stdout}\n${loaded.stderr}`.includes(imageReference)) {
      throw new LocalWorkerError(
        "INVALID",
        "ingestion-worker",
        `archive did not load the required ${imageReference} tag`,
      );
    }
    archiveLoaded = true;
  }

  const recordedImageDigest = await readRecordedImageDigest(contract);
  if (
    (archiveLoaded || recordedImageDigest !== undefined) &&
    (await commandSucceeds("podman", ["image", "exists", imageReference]))
  ) {
    try {
      const verified = await verifyImageContract(
        contract,
        ingestionManifest,
        archiveLoaded ? undefined : recordedImageDigest,
      );
      console.info(`Reusing verified ingestion image ${verified.imageDigest}`);
      return {
        ...verified,
        podmanClientVersion: podman.clientVersion,
        podmanServerVersion: podman.serverVersion,
      };
    } catch (error) {
      if (archiveLoaded) throw error;
      console.info("Rebuilding stale or mismatched local ingestion image");
    }
  } else if (
    !(await commandSucceeds("podman", ["image", "exists", imageReference]))
  ) {
    console.info("Building local ingestion image");
  } else {
    console.info(
      "Building the ingestion image because the existing tag has no recorded bootstrap identity",
    );
  }

  if (
    !(await commandSucceeds("git", [
      "diff",
      "--quiet",
      "HEAD",
      "--",
      contract.ingestion.context,
    ]))
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "worker sources are dirty; commit or isolate them before building provenance",
    );
  }
  const sourceRevision = (
    await runCommand("git", [
      "log",
      "-1",
      "--format=%H",
      "--",
      contract.ingestion.context,
    ])
  ).stdout.trim();
  if (!/^[a-f0-9]{40}$/.test(sourceRevision)) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "could not resolve the worker source revision",
    );
  }
  const containerfileRelativePath = path.relative(
    contract.ingestion.context,
    contract.ingestion.containerfile,
  );
  if (
    path.isAbsolute(containerfileRelativePath) ||
    containerfileRelativePath === ".." ||
    containerfileRelativePath.startsWith(`..${path.sep}`)
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "ingestion Containerfile escaped its build context",
    );
  }
  const trackedBuildRoot = await mkdtemp(
    path.join(tmpdir(), "reflo-ingestion-build-"),
  );
  const archivePath = path.join(trackedBuildRoot, "context.tar");
  const buildContext = path.join(trackedBuildRoot, "context");
  await ensureDirectory(buildContext);
  try {
    await runCommand("git", [
      "archive",
      "--format=tar",
      `--output=${archivePath}`,
      `${sourceRevision}:${contract.ingestion.context}`,
    ]);
    await runCommand("tar", [
      "--extract",
      "--file",
      archivePath,
      "--directory",
      buildContext,
    ]);
    await runCommand(
      "podman",
      [
        "build",
        "--platform",
        contract.ingestion.platform,
        "--target",
        "runtime",
        "--build-arg",
        `REFLO_SOURCE_COMMIT=${sourceRevision}`,
        "--tag",
        imageReference,
        "--file",
        path.join(buildContext, containerfileRelativePath),
        buildContext,
      ],
      { maxBuffer: 16 * maximumCommandOutputBytes, timeout: 30 * 60_000 },
    );
  } finally {
    await rm(trackedBuildRoot, { force: true, recursive: true });
  }
  const verified = await verifyImageContract(
    contract,
    ingestionManifest,
    undefined,
  );
  console.info(`Built ingestion image ${verified.imageDigest}`);
  return {
    ...verified,
    podmanClientVersion: podman.clientVersion,
    podmanServerVersion: podman.serverVersion,
  };
}

async function verifyImageContract(
  contract,
  ingestionManifest,
  expectedDigest,
) {
  const imageReference = contract.ingestion.imageReference;
  const inspect = await inspectImage(imageReference);
  const imageDigest = inspect.Digest;
  if (
    !digestPattern.test(imageDigest ?? "") ||
    (expectedDigest !== undefined && imageDigest !== expectedDigest) ||
    `${inspect.Os}/${inspect.Architecture}` !== contract.ingestion.platform ||
    inspect.Config?.User !== "65532:65532" ||
    JSON.stringify(inspect.Config?.Entrypoint) !==
      JSON.stringify(["java", "-jar", "/opt/reflo/worker.jar"]) ||
    inspect.Config?.Labels?.["org.opencontainers.image.version"] !==
      contract.ingestion.profile
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "local image identity, platform, user, entrypoint, or digest is invalid",
    );
  }
  const imageEnvironment = inspect.Config?.Env ?? [];
  if (
    imageEnvironment.some((entry) =>
      /(?:^|_)(?:ACCESS|AUTH|CREDENTIAL|PASSWORD|SECRET|TOKEN)(?:_|=)/i.test(
        entry,
      ),
    )
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "local image contains an ambient credential-shaped environment value",
    );
  }
  const sourceRevision =
    inspect.Config?.Labels?.["org.opencontainers.image.revision"];
  if (
    !/^[a-f0-9]{40}$/.test(sourceRevision ?? "") ||
    !(await commandSucceeds("git", [
      "cat-file",
      "-e",
      `${sourceRevision}^{commit}`,
    ]))
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "image source revision is missing from local Git history",
    );
  }
  if (
    !(await commandSucceeds("git", [
      "diff",
      "--quiet",
      sourceRevision,
      "--",
      contract.ingestion.context,
    ]))
  ) {
    throw new LocalWorkerError(
      "STALE",
      "ingestion-worker",
      "image source no longer matches the checked-in worker; run local-workers:prepare",
    );
  }
  const embeddedManifestOutput = (
    await runCommand(
      "podman",
      [
        "run",
        "--rm",
        "--pull=never",
        "--network=none",
        "--cap-drop=ALL",
        "--security-opt=no-new-privileges",
        "--read-only",
        "--user=65532:65532",
        "--userns=keep-id:uid=65532,gid=65532",
        `--cpus=${ingestionManifest.runtime.cpuCount}`,
        `--memory=${ingestionManifest.runtime.memoryBytes}`,
        `--pids-limit=${ingestionManifest.runtime.pids}`,
        `--tmpfs=/tmp:rw,noexec,nosuid,nodev,size=${ingestionManifest.runtime.temporaryStorageBytes}`,
        "--entrypoint=/bin/cat",
        imageReference,
        "/opt/reflo/worker-manifest.json",
      ],
      { timeout: 30_000 },
    )
  ).stdout;
  let embeddedManifest;
  try {
    embeddedManifest = JSON.parse(embeddedManifestOutput);
  } catch {
    throw new LocalWorkerError(
      "INVALID",
      "ingestion-worker",
      "embedded worker manifest is not valid JSON",
    );
  }
  if (JSON.stringify(embeddedManifest) !== JSON.stringify(ingestionManifest)) {
    throw new LocalWorkerError(
      "STALE",
      "ingestion-worker",
      "embedded worker manifest does not match the checked-in contract",
    );
  }
  return {
    imageDigest,
    imageReference,
    sourceRevision,
  };
}

