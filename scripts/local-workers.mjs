async function preparePiper(contract, runtime) {
  const targetDirectory = path.join(generatedRoot, "piper");
  const nextDirectory = path.join(generatedRoot, ".piper-next");
  const previousDirectory = path.join(generatedRoot, ".piper-previous");
  if (await pathExists(targetDirectory)) {
    try {
      const existingState = await readJson(statePath);
      await verifyPiperDirectory(contract, existingState.piper, runtime);
      console.info("Reusing verified Piper development environment");
      return existingState.piper;
    } catch {
      console.info("Rebuilding stale or mismatched Piper environment");
    }
  }
  await rm(nextDirectory, { force: true, recursive: true });
  await ensureDirectory(nextDirectory);
  const modelPath = path.join(
    nextDirectory,
    path.basename(contract.piper.voice.modelPath),
  );
  const configPath = path.join(
    nextDirectory,
    path.basename(contract.piper.voice.configPath),
  );
  await materializeVoiceArtifact(
    contract,
    "model",
    modelPath,
    contract.piper.voice.modelSha256,
  );
  await materializeVoiceArtifact(
    contract,
    "config",
    configPath,
    contract.piper.voice.configSha256,
  );

  const bootstrapPython = await findBootstrapPython(contract);
  const downloads = path.join(nextDirectory, "downloads");
  await ensureDirectory(downloads);
  console.info(
    `Downloading checksum-pinned Piper ${contract.piper.version} runtime wheels`,
  );
  await runCommand(
    bootstrapPython,
    [
      "-m",
      "pip",
      "download",
      "--disable-pip-version-check",
      "--no-deps",
      "--only-binary=:all:",
      "--dest",
      downloads,
      `piper-tts==${contract.piper.version}`,
      `onnxruntime==${runtime.onnxRuntimeVersion}`,
    ],
    { timeout: 5 * 60_000 },
  );
  const piperWheelPath = path.join(downloads, runtime.piperWheel);
  const onnxWheelPath = path.join(downloads, runtime.onnxRuntimeWheel);
  await requireDigest(piperWheelPath, runtime.piperWheelSha256, "piper");
  await requireDigest(onnxWheelPath, runtime.onnxRuntimeWheelSha256, "piper");

  const venvDirectory = path.join(nextDirectory, "venv");
  await runCommand(bootstrapPython, ["-m", "venv", venvDirectory], {
    timeout: 120_000,
  });
  const pythonExecutable = path.join(venvDirectory, "bin", "python");
  console.info("Installing exact Piper development dependency versions");
  await runCommand(
    pythonExecutable,
    [
      "-m",
      "pip",
      "install",
      "--disable-pip-version-check",
      "--no-cache-dir",
      "--only-binary=:all:",
      ...contract.piper.dependencies,
    ],
    { maxBuffer: 4 * maximumCommandOutputBytes, timeout: 10 * 60_000 },
  );
  await runCommand(
    pythonExecutable,
    [
      "-m",
      "pip",
      "install",
      "--disable-pip-version-check",
      "--no-cache-dir",
      "--no-deps",
      "--no-index",
      "--find-links",
      downloads,
      `piper-tts==${contract.piper.version}`,
      `onnxruntime==${runtime.onnxRuntimeVersion}`,
    ],
    { maxBuffer: 4 * maximumCommandOutputBytes, timeout: 5 * 60_000 },
  );
  const packageIdentity = await inspectPiperPackages(
    pythonExecutable,
    contract,
    runtime,
  );
  const preflightWavPath = path.join(nextDirectory, "preflight.wav");
  const candidate = {
    artifactRevision: contract.piper.voice.revision,
    configPath,
    configSha256: contract.piper.voice.configSha256,
    environmentSha256: packageIdentity.environmentSha256,
    modelPath,
    modelSha256: contract.piper.voice.modelSha256,
    onnxRuntimeVersion: runtime.onnxRuntimeVersion,
    onnxRuntimeWheel: runtime.onnxRuntimeWheel,
    onnxRuntimeWheelSha256: runtime.onnxRuntimeWheelSha256,
    packageFreeze: packageIdentity.packageFreeze,
    piperVersion: contract.piper.version,
    piperWheel: runtime.piperWheel,
    piperWheelSha256: runtime.piperWheelSha256,
    platform: runtime.platform,
    preflightWavPath,
    pythonVersion: packageIdentity.pythonVersion,
    pythonExecutable,
    voiceArtifactVersion: contract.piper.voiceArtifactVersion,
    voiceId: contract.piper.voice.voiceId,
  };
  await synthesizePiper(candidate, preflightWavPath);
  await inspectWav(preflightWavPath);

  await rm(previousDirectory, { force: true, recursive: true });
  if (await pathExists(targetDirectory)) {
    await rename(targetDirectory, previousDirectory);
  }
  await rename(nextDirectory, targetDirectory);
  await rm(previousDirectory, { force: true, recursive: true });
  const final = rebasePiperPaths(candidate, nextDirectory, targetDirectory);
  console.info(`Verified Piper ${final.piperVersion} with ${final.voiceId}`);
  return final;
}

async function materializeVoiceArtifact(
  contract,
  kind,
  destination,
  expectedSha256,
) {
  const legacy = path.join(
    repositoryRoot,
    ".reflo",
    "local-smoke",
    "piper",
    path.basename(destination),
  );
  if (await regularFileMatches(legacy, expectedSha256).catch(() => false)) {
    await copyFile(legacy, destination);
  } else {
    const relativePath =
      kind === "model"
        ? contract.piper.voice.modelPath
        : contract.piper.voice.configPath;
    const url = `https://raw.githubusercontent.com/${contract.piper.voice.repository}/${contract.piper.voice.revision}/${relativePath}`;
    await downloadExact(url, destination, expectedSha256, "piper");
  }
  await chmod(destination, 0o400);
}

async function findBootstrapPython(contract) {
  const configured = process.env.REFLO_LOCAL_PIPER_BOOTSTRAP_PYTHON;
  const executable =
    configured === undefined || configured.length === 0
      ? "python3.13"
      : safeAbsoluteInput(configured, "REFLO_LOCAL_PIPER_BOOTSTRAP_PYTHON");
  let version;
  try {
    version = (
      await runCommand(executable, ["--version"], { timeout: 10_000 })
    ).stdout.trim();
  } catch {
    throw new LocalWorkerError(
      "UNSUPPORTED",
      "piper",
      `install Python ${contract.piper.pythonVersion} or set REFLO_LOCAL_PIPER_BOOTSTRAP_PYTHON`,
    );
  }
  if (version !== `Python ${contract.piper.pythonVersion}`) {
    throw new LocalWorkerError(
      "UNSUPPORTED",
      "piper",
      `${version}; expected exactly Python ${contract.piper.pythonVersion}`,
    );
  }
  return executable;
}

async function inspectPiperPackages(pythonExecutable, contract, runtime) {
  const pythonVersion = (
    await runCommand(pythonExecutable, ["--version"], { timeout: 10_000 })
  ).stdout.trim();
  if (pythonVersion !== `Python ${contract.piper.pythonVersion}`) {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      `${pythonVersion}; expected exactly Python ${contract.piper.pythonVersion}`,
    );
  }
  const output = (
    await runCommand(
      pythonExecutable,
      [
        "-c",
        [
          "import importlib.metadata as m",
          "import json",
          "names=['piper-tts','onnxruntime']",
          "print(json.dumps({name:m.version(name) for name in names},sort_keys=True))",
        ].join(";"),
      ],
      { timeout: 30_000 },
    )
  ).stdout.trim();
  let versions;
  try {
    versions = JSON.parse(output);
  } catch {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      "could not inspect the Piper Python environment",
    );
  }
  if (
    versions["piper-tts"] !== contract.piper.version ||
    versions.onnxruntime !== runtime.onnxRuntimeVersion
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      "installed Piper or ONNX Runtime version is not pinned",
    );
  }
  const packageFreeze = (
    await runCommand(pythonExecutable, ["-m", "pip", "freeze", "--all"], {
      timeout: 30_000,
    })
  ).stdout
    .trim()
    .split("\n")
    .filter((line) => line.length > 0)
    .sort();
  for (const dependency of contract.piper.dependencies) {
    if (!packageFreeze.includes(dependency)) {
      throw new LocalWorkerError(
        "INVALID",
        "piper",
        `installed environment is missing ${dependency}`,
      );
    }
  }
  const identity = [
    `python=${contract.piper.pythonVersion}`,
    `piper=${runtime.piperWheelSha256}`,
    `onnxruntime=${runtime.onnxRuntimeWheelSha256}`,
    ...packageFreeze,
  ].join("\n");
  return {
    environmentSha256: sha256Bytes(Buffer.from(identity, "utf8")),
    packageFreeze,
    pythonVersion: contract.piper.pythonVersion,
  };
}

async function verifyPiperDirectory(contract, state, runtime) {
  const piperDirectory = path.join(generatedRoot, "piper");
  if (
    state === undefined ||
    !piperStatePathsMatch(state, piperDirectory, contract.piper.voice) ||
    state.platform !== runtime.platform ||
    state.pythonVersion !== contract.piper.pythonVersion ||
    state.piperVersion !== contract.piper.version ||
    state.piperWheel !== runtime.piperWheel ||
    state.piperWheelSha256 !== runtime.piperWheelSha256 ||
    state.onnxRuntimeVersion !== runtime.onnxRuntimeVersion ||
    state.onnxRuntimeWheel !== runtime.onnxRuntimeWheel ||
    state.onnxRuntimeWheelSha256 !== runtime.onnxRuntimeWheelSha256 ||
    state.voiceArtifactVersion !== contract.piper.voiceArtifactVersion ||
    state.artifactRevision !== contract.piper.voice.revision ||
    state.modelSha256 !== contract.piper.voice.modelSha256 ||
    state.configSha256 !== contract.piper.voice.configSha256
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      "recorded Piper identities do not match the checked-in contract",
    );
  }
  await Promise.all([
    requireDigest(state.modelPath, state.modelSha256, "piper"),
    requireDigest(state.configPath, state.configSha256, "piper"),
    requireDigest(
      path.join(
        path.dirname(path.dirname(path.dirname(state.pythonExecutable))),
        "downloads",
        state.piperWheel,
      ),
      state.piperWheelSha256,
      "piper",
    ),
    requireDigest(
      path.join(
        path.dirname(path.dirname(path.dirname(state.pythonExecutable))),
        "downloads",
        state.onnxRuntimeWheel,
      ),
      state.onnxRuntimeWheelSha256,
      "piper",
    ),
  ]);
  const inspected = await inspectPiperPackages(
    state.pythonExecutable,
    contract,
    runtime,
  );
  if (
    inspected.environmentSha256 !== state.environmentSha256 ||
    JSON.stringify(inspected.packageFreeze) !==
      JSON.stringify(state.packageFreeze)
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      "Piper Python environment changed after preparation",
    );
  }
  await inspectWav(state.preflightWavPath);
}

