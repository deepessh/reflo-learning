function rebasePiperPaths(state, from, to) {
  const rebase = (value) =>
    value === from
      ? to
      : value.startsWith(from + path.sep)
        ? to + value.slice(from.length)
        : value;
  return {
    ...state,
    configPath: rebase(state.configPath),
    modelPath: rebase(state.modelPath),
    preflightWavPath: rebase(state.preflightWavPath),
    pythonExecutable: rebase(state.pythonExecutable),
  };
}

