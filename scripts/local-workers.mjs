async function inspectWav(filePath) {
  const bytes = await readFile(filePath);
  if (
    bytes.byteLength < 44 ||
    bytes.subarray(0, 4).toString("ascii") !== "RIFF" ||
    bytes.subarray(8, 12).toString("ascii") !== "WAVE"
  ) {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      "Piper output is not a playable WAV file",
    );
  }
  const sampleRate = bytes.readUInt32LE(24);
  if (sampleRate !== 22_050 && sampleRate !== 24_000) {
    throw new LocalWorkerError(
      "INVALID",
      "piper",
      `Piper WAV sample rate ${sampleRate} is unsupported`,
    );
  }
  return { byteLength: bytes.byteLength, sampleRate };
}

